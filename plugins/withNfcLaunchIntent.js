/**
 * Expo config plugin: logs a drink when the registered sticker is tapped while
 * HydraTap is NOT open — without opening HydraTap and without writing anything to
 * the sticker.
 *
 * Android's tag dispatch must start an Activity for an NFC tap (it cannot start a
 * background service), so this plugin adds `NfcTapActivity`: an invisible, translucent
 * activity in its own task, excluded from Recents. It receives:
 *   - TECH_DISCOVERED for blank stickers (NFC-A/B/F/V tech lists), and
 *   - NDEF_DISCOVERED for empty-record stickers and for stickers carrying the
 *     `hydratap://log?key=…` link written by earlier builds.
 * It reads the sticker's hardware UID from the intent and, only if it matches the
 * registered sticker (or the old link's key matches), records the tap as a JSON file in
 * filesDir/hydratap-bridge/taps/ (imported into SQLite by the app, see
 * src/bridge/tapBridge.ts; 8 s duplicate protection), cancels today's remaining
 * reminders once the goal is reached, shows a small toast plus a short vibration, and
 * finishes. Any other tag is silently ignored. It never opens the SQLite database.
 *
 * Android dispatch order: a sticker whose data another app handles (e.g. a website
 * link → browser) goes to that app first; blank stickers come here.
 *
 * Lock screen: the activity may run over the keyguard (setShowWhenLocked). Android only
 * reads stickers on the lock screen if the phone's "Require device unlock for NFC"
 * setting is off, and never with the screen off.
 */
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('expo/config-plugins');

const ACTIVITY = '.NfcTapActivity';

function kotlinSource(pkg) {
  return `package ${pkg}

import android.app.Activity
import android.content.Context
import android.content.Intent
import android.net.Uri
import android.nfc.NfcAdapter
import android.nfc.Tag
import android.os.Build
import android.os.Bundle
import android.os.VibrationEffect
import android.os.Vibrator
import android.widget.Toast
import org.json.JSONObject
import java.io.File
import java.util.Calendar
import java.util.Locale

/**
 * Invisible activity started by Android when the HydraTap sticker is tapped while the
 * app isn't in front. Records the drink for HydraTap to import, shows a small toast and
 * finishes, so HydraTap's UI never opens. Generated by plugins/withNfcLaunchIntent.js.
 */
class NfcTapActivity : Activity() {
  override fun onCreate(savedInstanceState: Bundle?) {
    super.onCreate(savedInstanceState)
    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O_MR1) setShowWhenLocked(true)
    val launchedFromHistory = ((intent?.flags ?: 0) and Intent.FLAG_ACTIVITY_LAUNCHED_FROM_HISTORY) != 0
    val action = intent?.action
    val isNfc = action == NfcAdapter.ACTION_TECH_DISCOVERED ||
      action == NfcAdapter.ACTION_NDEF_DISCOVERED ||
      action == NfcAdapter.ACTION_TAG_DISCOVERED
    if (!launchedFromHistory && isNfc) {
      try {
        handle(tagUid(intent), intent.data)
      } catch (e: Exception) {
        // Never crash on a tap; HydraTap re-syncs when opened.
      }
    }
    finish()
    @Suppress("DEPRECATION")
    overridePendingTransition(0, 0)
  }

  @Suppress("DEPRECATION")
  private fun tagUid(i: Intent): String? {
    val tag: Tag? = if (Build.VERSION.SDK_INT >= 33) {
      i.getParcelableExtra(NfcAdapter.EXTRA_TAG, Tag::class.java)
    } else {
      i.getParcelableExtra<Tag>(NfcAdapter.EXTRA_TAG)
    }
    val id = tag?.id ?: return null
    if (id.isEmpty()) return null
    return id.joinToString("") { String.format(Locale.US, "%02X", it.toInt() and 0xFF) }
  }

  private fun handle(uid: String?, uri: Uri?) {
    val key = if (uri != null && uri.scheme == "hydratap") uri.getQueryParameter("key") else null
    val result = logDrink(uid, key) ?: return // not our sticker / not set up: stay silent
    toast(result)
    buzz()
  }

  /**
   * Records the tap as a small JSON file in hydratap-bridge/taps/ (the app imports it
   * into its database on next open). Never touches HydraTap's SQLite file: the app uses
   * expo-sqlite's own SQLite build, and two SQLite libraries in one process can't share
   * a database safely. Returns the toast text, or null if this isn't the registered
   * sticker or the app isn't set up.
   */
  private fun logDrink(uid: String?, key: String?): String? {
    val dir = File(filesDir, "hydratap-bridge")
    val stateFile = File(dir, "state.json")
    if (!stateFile.exists()) return null
    val s = JSONObject(stateFile.readText())
    if (!s.optBoolean("onboarded", false)) return null
    val stickerUid = if (s.isNull("stickerUid")) "" else s.optString("stickerUid", "")
    val uidMatches = uid != null && stickerUid.isNotEmpty() && uid.equals(stickerUid, ignoreCase = true)
    val linkKey = s.optString("linkKey", "")
    val keyMatches = !key.isNullOrEmpty() && linkKey.isNotEmpty() && key == linkKey
    if (!uidMatches && !keyMatches) return null

    val goal = s.optLong("goalMl", 2500L)
    val amount = s.optLong("scanAmountMl", 250L)
    val now = System.currentTimeMillis()
    val day = dayKey(now)

    // Taps logged here that the app hasn't imported yet.
    val tapsDir = File(dir, "taps")
    tapsDir.mkdirs()
    var pendingToday = 0L
    var lastPending = 0L
    tapsDir.listFiles()?.forEach { f ->
      if (!f.name.endsWith(".json")) return@forEach
      try {
        val t = JSONObject(f.readText())
        val at = t.optLong("at", 0L)
        if (at > lastPending) lastPending = at
        if (dayKey(at) == day) pendingToday += t.optLong("amountMl", 0L)
      } catch (e: Exception) {
        // ignore a broken file
      }
    }

    val lastInApp = if (s.isNull("lastScanAt")) 0L else s.optLong("lastScanAt", 0L)
    val last = maxOf(lastInApp, lastPending)
    if (last > 0L && now - last in 0L until COOLDOWN_MS) return "\uD83D\uDCA7 Already logged"

    val tap = JSONObject()
      .put("at", now)
      .put("amountMl", amount)
      .put("goalMl", goal)
      .put("tagId", if (stickerUid.isNotEmpty()) stickerUid else JSONObject.NULL)
    val tmp = File(tapsDir, "$now.tmp")
    tmp.writeText(tap.toString())
    if (!tmp.renameTo(File(tapsDir, "$now.json"))) {
      tmp.delete()
      return null
    }

    val base = if (s.optString("day", "") == day) s.optLong("todayTotalMl", 0L) else 0L
    val before = base + pendingToday
    val total = before + amount
    if (before < goal && total >= goal) {
      cancelTodaysReminders(s.optJSONObject("reminders"), day)
      return "\uD83C\uDF89 +$amount ml \u00B7 daily goal reached!"
    }
    val left = goal - total
    return if (left > 0) "\uD83D\uDCA7 +$amount ml \u00B7 \${volume(left)} to go" else "\uD83D\uDCA7 +$amount ml \u00B7 goal done"
  }

  /** Same ids as src/notifications/reminders.ts: hydratap-reminder-YYYY-MM-DD-MMMM (minute of day). */
  private fun cancelTodaysReminders(reminders: JSONObject?, day: String) {
    if (reminders == null || !reminders.optBoolean("enabled", false)) return
    val interval = reminders.optInt("intervalMin", 60)
    val start = reminders.optInt("startMin", 540)
    val end = reminders.optInt("endMin", 1260)
    if (interval <= 0) return
    val ids = ArrayList<String>()
    var m = start
    while (m <= end && m < 24 * 60) {
      ids.add(String.format(Locale.US, "hydratap-reminder-%s-%04d", day, m))
      m += interval
    }
    try {
      // expo-notifications' own API, called reflectively so a library change can't break the build.
      val cls = Class.forName("expo.modules.notifications.service.NotificationsService")
      val companion = cls.getField("Companion").get(null)
      companion.javaClass
        .getMethod("removeScheduledNotifications", Context::class.java, Collection::class.java, android.os.ResultReceiver::class.java)
        .invoke(companion, applicationContext, ids, null)
    } catch (e: Exception) {
      // HydraTap re-plans reminders the next time it opens.
    }
  }

  private fun dayKey(ts: Long): String {
    val c = Calendar.getInstance()
    c.timeInMillis = ts
    return String.format(Locale.US, "%04d-%02d-%02d", c.get(Calendar.YEAR), c.get(Calendar.MONTH) + 1, c.get(Calendar.DAY_OF_MONTH))
  }

  private fun volume(ml: Long): String {
    if (ml < 1000) return "$ml ml"
    return String.format(Locale.US, "%.2f", ml / 1000.0).trimEnd('0').trimEnd('.') + " L"
  }

  private fun toast(text: String) {
    Toast.makeText(applicationContext, text, Toast.LENGTH_SHORT).show()
  }

  private fun buzz() {
    try {
      @Suppress("DEPRECATION")
      val v = getSystemService(Context.VIBRATOR_SERVICE) as? Vibrator ?: return
      if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
        v.vibrate(VibrationEffect.createWaveform(longArrayOf(0, 35, 70, 35), -1))
      } else {
        @Suppress("DEPRECATION")
        v.vibrate(longArrayOf(0, 35, 70, 35), -1)
      }
    } catch (e: Exception) {
      // vibration is optional
    }
  }

  companion object {
    private const val COOLDOWN_MS = 8000L
  }
}
`;
}

// A blank sticker matches if it supports every tech of any one list.
const TECH_FILTER_XML = `<?xml version="1.0" encoding="utf-8"?>
<resources xmlns:xliff="urn:oasis:names:tc:xliff:document:1.2">
  <tech-list><tech>android.nfc.tech.NfcA</tech></tech-list>
  <tech-list><tech>android.nfc.tech.NfcB</tech></tech-list>
  <tech-list><tech>android.nfc.tech.NfcF</tech></tech-list>
  <tech-list><tech>android.nfc.tech.NfcV</tech></tech-list>
</resources>
`;

function withNfcTapActivitySource(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const pkg = cfg.android?.package;
      if (!pkg) throw new Error('[withNfcLaunchIntent] expo.android.package is required.');
      const main = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main');
      const dir = path.join(main, 'java', ...pkg.split('.'));
      await fs.promises.mkdir(dir, { recursive: true });
      await fs.promises.writeFile(path.join(dir, 'NfcTapActivity.kt'), kotlinSource(pkg));
      const xmlDir = path.join(main, 'res', 'xml');
      await fs.promises.mkdir(xmlDir, { recursive: true });
      await fs.promises.writeFile(path.join(xmlDir, 'hydratap_nfc_tech_filter.xml'), TECH_FILTER_XML);
      return cfg;
    },
  ]);
}

function withNfcTapActivityManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    const manifest = cfg.modResults;
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(manifest);
    app.activity = (app.activity ?? []).filter((a) => a.$?.['android:name'] !== ACTIVITY);
    app.activity.push({
      $: {
        'android:name': ACTIVITY,
        'android:exported': 'true',
        'android:theme': '@android:style/Theme.Translucent.NoTitleBar',
        'android:excludeFromRecents': 'true',
        'android:noHistory': 'true',
        'android:taskAffinity': '',
        'android:launchMode': 'singleTask',
      },
      'intent-filter': [
        {
          // Blank stickers (no NDEF data): matched by technology.
          action: [{ $: { 'android:name': 'android.nfc.action.TECH_DISCOVERED' } }],
          category: [{ $: { 'android:name': 'android.intent.category.DEFAULT' } }],
        },
        {
          // Stickers whose NDEF message has an empty / data-less first record.
          action: [{ $: { 'android:name': 'android.nfc.action.NDEF_DISCOVERED' } }],
          category: [{ $: { 'android:name': 'android.intent.category.DEFAULT' } }],
        },
        {
          // Stickers written by earlier HydraTap builds.
          action: [{ $: { 'android:name': 'android.nfc.action.NDEF_DISCOVERED' } }],
          category: [{ $: { 'android:name': 'android.intent.category.DEFAULT' } }],
          data: [
            { $: { 'android:scheme': 'hydratap', 'android:host': 'log' } },
            { $: { 'android:scheme': 'hydratap', 'android:host': 'nfc' } },
          ],
        },
      ],
      'meta-data': [
        {
          $: {
            'android:name': 'android.nfc.action.TECH_DISCOVERED',
            'android:resource': '@xml/hydratap_nfc_tech_filter',
          },
        },
      ],
    });

    // NFC hardware is optional: the app still works (manual logging) without it.
    manifest.manifest['uses-feature'] = (manifest.manifest['uses-feature'] ?? []).filter(
      (f) => f.$?.['android:name'] !== 'android.hardware.nfc',
    );
    manifest.manifest['uses-feature'].push({
      $: { 'android:name': 'android.hardware.nfc', 'android:required': 'false' },
    });
    return cfg;
  });
}

module.exports = (config) => withNfcTapActivityManifest(withNfcTapActivitySource(config));
